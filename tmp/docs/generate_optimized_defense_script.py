def set_east_asian_font(run, font_name: str = "宋体") -> None:
    run.font.name = font_name
    run._element.rPr.rFonts.set(qn("w:eastAsia"), font_name)


def set_document_defaults(doc: Document) -> None:
    styles = doc.styles
    styles["Normal"].font.name = "宋体"
    styles["Normal"].font.size = Pt(11)
    styles["Normal"]._element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")
    for style_name in ["Heading 1", "Heading 2"]:
        style = styles[style_name]
        style.font.name = "黑体"
        style._element.rPr.rFonts.set(qn("w:eastAsia"), "黑体")
    section = doc.sections[0]
    section.top_margin = Pt(54)
    section.bottom_margin = Pt(54)
    section.left_margin = Pt(63)
    section.right_margin = Pt(63)


def add_line_spacing(paragraph, value: int = 360) -> None:
    p_pr = paragraph._element.get_or_add_pPr()
    spacing = p_pr.find(qn("w:spacing"))
    if spacing is None:
        spacing = OxmlElement("w:spacing")
        p_pr.append(spacing)
    spacing.set(qn("w:line"), str(value))
    spacing.set(qn("w:lineRule"), "auto")
    spacing.set(qn("w:after"), "120")


def write_markdown() -> None:
    lines = [
        "# 答辩个人陈述讲稿（优化版）",
        "",
        "> 建议总时长：约13-15分钟。语气定位：正式、清楚、口语化，避免按论文原文朗读。",
        "",
    ]
    for title, timing, text in slides:
        lines.append(f"## {title}（{timing}）")
        lines.append("")
        lines.append(text)
        lines.append("")
    MD_OUT.write_text("\n".join(lines), encoding="utf-8")


def write_docx() -> None:
    doc = Document()
    set_document_defaults(doc)

    title = doc.add_heading("答辩个人陈述讲稿（优化版）", level=1)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    note = doc.add_paragraph("建议总时长：约13-15分钟。语气定位：正式、清楚、口语化，避免按论文原文朗读。")
    note.alignment = WD_ALIGN_PARAGRAPH.CENTER
    for run in note.runs:
        set_east_asian_font(run, "宋体")
    add_line_spacing(note)

    for slide_title, timing, body in slides:
        heading = doc.add_heading(f"{slide_title}（{timing}）", level=2)
        for run in heading.runs:
            set_east_asian_font(run, "黑体")
        para = doc.add_paragraph(body)
        para.paragraph_format.first_line_indent = Pt(22)
        add_line_spacing(para)
        for run in para.runs:
            set_east_asian_font(run, "宋体")

    doc.save(DOCX_OUT)


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    write_markdown()
    write_docx()
    print(DOCX_OUT)
    print(MD_OUT)


if __name__ == "__main__":
    main()
